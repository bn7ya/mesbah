from __future__ import annotations

import hashlib
import importlib
from pathlib import Path

import pytest
from django.apps import apps
from django.db.migrations.loader import MigrationLoader

from contracts import Contract

GENERATED: str = "# Generated by Django"


def fingerprint(module: str) -> str:
    source: str | None = importlib.import_module(module).__file__
    assert source is not None
    lines: list[str] = Path(source).read_text(encoding="utf-8").splitlines()
    kept: str = "\n".join(line for line in lines if not line.startswith(GENERATED))
    return hashlib.sha256(kept.encode()).hexdigest()


@pytest.mark.contract
def test_shipped_migrations_never_change(contract: Contract) -> None:
    ours: set[str] = {
        config.label for config in apps.get_app_configs() if config.name.startswith("apps.")
    }
    loader: MigrationLoader = MigrationLoader(None, ignore_no_migrations=True)
    shipped: dict[str, dict[str, str]] = {}
    for (label, name), migration in loader.disk_migrations.items():
        if label in ours:
            shipped.setdefault(label, {})[name] = fingerprint(migration.__module__)

    contract.check("migrations.json", shipped)
